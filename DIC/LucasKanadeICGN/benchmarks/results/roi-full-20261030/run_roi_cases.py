"""Run the masked half of the qualification using the public benchmark CLI.

Run from the repository root with PYTHONPATH set to its Python src directory.
Pass the mask directory generated by generate_masks.py as the first argument.
"""
import os
import subprocess
import sys
from pathlib import Path

reports = Path(__file__).resolve().parent
benchmark = reports.parents[1] / "benchmark_image_to_field.py"
for model in ("translation", "affine"):
    for case in ("baseline-recheck", "none", "full", "baseline-afterfull", "large", "small", "fragmented"):
        command = [sys.executable, str(benchmark), "--backend", "native-pyramid",
                   "--device-type", "gpu", "--motion-model", model,
                   "--outlier-policy", "median", "--frames", "160", "--warmups", "12",
                   "--campaigns", "3", "--pipeline-depth", "2"]
        if case in ("full", "large", "small", "fragmented"):
            command.extend(["--roi-mask", str(Path(sys.argv[1]) / f"{case}.npy")])
        environment = os.environ.copy()
        if case.startswith("baseline-"):
            environment["PYTHONPATH"] = sys.argv[2]
        path = reports / (f"{case}-{model}.json" if case.startswith("baseline-") else f"candidate-{model}-{case}.json")
        with path.open("w") as stream:
            subprocess.run(command, stdout=stream, check=True, env=environment)
        print(path.name, flush=True)
